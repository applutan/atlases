#!/usr/bin/env python3
"""
affine_macro_orbits.py - Analysis and Enumeration of Affine Macro-Orbits of Mosaic Partitions

Computes the macro-orbit structure of set partitions under the outer automorphism group
    G_macro = Aff(Z_n) / D_n = (Z_n)* / {+-1}
using Burnside's Lemma on the affine group action.

Supports arbitrary n and equal-block shapes z_k^m (where n = k * m).
"""

import sys
import os
import math
import argparse
import itertools
from collections import defaultdict

def get_units(n):
    return [a for a in range(1, n) if math.gcd(a, n) == 1]

def get_affine_group(n):
    """Return all elements of Aff(Z_n) as (a, b) representing x -> (a*x + b) % n."""
    units = get_units(n)
    return [(a, b) for a in units for b in range(n)]

def get_element_cycle_decomposition(perm):
    """Given a permutation perm as a dict or list mapping 0..n-1 to 0..n-1, return list of cycles."""
    n = len(perm)
    visited = [False] * n
    cycles = []
    for i in range(n):
        if not visited[i]:
            cyc = []
            curr = i
            while not visited[curr]:
                visited[curr] = True
                cyc.append(curr)
                curr = perm[curr]
            cycles.append(tuple(cyc))
    return cycles

def count_fixed_partitions(perm, k_blocks, block_size):
    n = k_blocks * block_size
    if all(perm[i] == i for i in range(n)):
        total = math.factorial(n)
        for _ in range(k_blocks):
            total //= math.factorial(block_size)
        total //= math.factorial(k_blocks)
        return total
    return len(get_fixed_partitions(perm, k_blocks, block_size))

def get_fixed_partitions(perm, k_blocks, block_size):
    """Return the set of all partitions fixed by perm."""
    n = k_blocks * block_size
    visited = [False] * n
    cycles = []
    for i in range(n):
        if not visited[i]:
            c = []
            curr = i
            while not visited[curr]:
                visited[curr] = True
                c.append(curr)
                curr = perm[curr]
            cycles.append(tuple(c))
            
    total_valid_partitions = set()
    
    for sigma in itertools.permutations(range(k_blocks)):
        valid_b_for_cycle = []
        possible = True
        for C in cycles:
            L_C = len(C)
            allowed_b = []
            for b in range(k_blocks):
                curr_b = b
                for _ in range(L_C):
                    curr_b = sigma[curr_b]
                if curr_b == b:
                    allowed_b.append(b)
            if not allowed_b:
                possible = False
                break
            valid_b_for_cycle.append(allowed_b)
            
        if not possible:
            continue
            
        current_partition = [[] for _ in range(k_blocks)]
        
        def backtrack(cycle_idx, current_sizes):
            if cycle_idx == len(cycles):
                if current_sizes == tuple([block_size] * k_blocks):
                    part = frozenset(frozenset(current_partition[b]) for b in range(k_blocks))
                    total_valid_partitions.add(part)
                return
            
            C = cycles[cycle_idx]
            for b in valid_b_for_cycle[cycle_idx]:
                curr_b = b
                counts = [0] * k_blocks
                for _ in C:
                    counts[curr_b] += 1
                    curr_b = sigma[curr_b]
                
                if all(current_sizes[i] + counts[i] <= block_size for i in range(k_blocks)):
                    new_sizes = tuple(current_sizes[i] + counts[i] for i in range(k_blocks))
                    curr_b = b
                    for x in C:
                        current_partition[curr_b].append(x)
                        curr_b = sigma[curr_b]
                        
                    backtrack(cycle_idx + 1, new_sizes)
                    
                    curr_b = b
                    for _ in C:
                        current_partition[curr_b].pop()
                        curr_b = sigma[curr_b]
                        
        backtrack(0, tuple([0] * k_blocks))
        
    return total_valid_partitions

def find_fixed_point_orbits(n, k_blocks, block_size):
    """
    Find all D_n orbits that are fixed by G_macro = (Z_n)* / {+-1}.
    Since G_macro is cyclic generated by mu_3 (for n=16), an orbit O is fixed iff
    it contains a partition fixed by some element in D_n * mu_3.
    """
    d_n_elements = [(a, b) for a in [1, n - 1] for b in range(n)]
    
    # We find all partitions fixed by any affine element with multiplier in {3, n-3}
    mu3_units = [3, (n - 3) % n]
    candidate_partitions = set()
    for a in mu3_units:
        for b in range(n):
            perm = [(a * x + b) % n for x in range(n)]
            parts = get_fixed_partitions(perm, k_blocks, block_size)
            candidate_partitions.update(parts)
            
    # Group candidate partitions into D_n orbits
    visited = set()
    fixed_orbits = []
    
    def apply_d_action(part, a, b):
        return frozenset(frozenset((a * x + b) % n for x in blk) for blk in part)
        
    for p in candidate_partitions:
        if p in visited:
            continue
        orb = set()
        for a, b in d_n_elements:
            orb.add(apply_d_action(p, a, b))
        visited.update(orb)
        
        # Verify that mu_3 preserves this orbit
        p_mu3 = frozenset(frozenset((3 * x) % n for x in blk) for blk in p)
        if p_mu3 in orb:
            fixed_orbits.append(orb)
            
    return fixed_orbits
    """
    Count the number of set partitions of {0..n-1} into k_blocks each of size block_size
    that are invariant under the permutation perm (given as a list of length n = k_blocks * block_size).
    """
    n = k_blocks * block_size
    
    # Check if perm is identity
    if all(perm[i] == i for i in range(n)):
        # Analytical multinomial coefficient / k_blocks!
        total = math.factorial(n)
        for _ in range(k_blocks):
            total //= math.factorial(block_size)
        total //= math.factorial(k_blocks)
        return total

    # Find cycles of perm
    visited = [False] * n
    cycles = []
    for i in range(n):
        if not visited[i]:
            c = []
            curr = i
            while not visited[curr]:
                visited[curr] = True
                c.append(curr)
                curr = perm[curr]
            cycles.append(tuple(c))
            
    # For a partition to be invariant under perm, perm must induce a permutation sigma in S_{k_blocks}
    # on the blocks.
    # Total valid partitions (as set of canonical frozensets of blocks)
    total_valid_partitions = set()
    
    # All permutations of {0..k_blocks-1}
    for sigma in itertools.permutations(range(k_blocks)):
        # Precompute allowed blocks for each cycle
        valid_b_for_cycle = []
        possible = True
        for C in cycles:
            L_C = len(C)
            allowed_b = []
            for b in range(k_blocks):
                curr_b = b
                for _ in range(L_C):
                    curr_b = sigma[curr_b]
                if curr_b == b:
                    allowed_b.append(b)
            if not allowed_b:
                possible = False
                break
            valid_b_for_cycle.append(allowed_b)
            
        if not possible:
            continue
            
        # Backtrack over assigning each cycle to an allowed starting block b
        current_partition = [[] for _ in range(k_blocks)]
        
        def backtrack(cycle_idx, current_sizes):
            if cycle_idx == len(cycles):
                if current_sizes == tuple([block_size] * k_blocks):
                    part = frozenset(frozenset(current_partition[b]) for b in range(k_blocks))
                    total_valid_partitions.add(part)
                return
            
            C = cycles[cycle_idx]
            for b in valid_b_for_cycle[cycle_idx]:
                # Trace elements of C
                curr_b = b
                counts = [0] * k_blocks
                for _ in C:
                    counts[curr_b] += 1
                    curr_b = sigma[curr_b]
                
                # Check capacity
                if all(current_sizes[i] + counts[i] <= block_size for i in range(k_blocks)):
                    new_sizes = tuple(current_sizes[i] + counts[i] for i in range(k_blocks))
                    curr_b = b
                    for x in C:
                        current_partition[curr_b].append(x)
                        curr_b = sigma[curr_b]
                        
                    backtrack(cycle_idx + 1, new_sizes)
                    
                    curr_b = b
                    for _ in C:
                        current_partition[curr_b].pop()
                        curr_b = sigma[curr_b]
                        
        backtrack(0, tuple([0] * k_blocks))
        
    return len(total_valid_partitions)

def analyze_macro_group(n):
    """Analyze the structure of G_macro = (Z_n)* / {+-1}."""
    units = get_units(n)
    inv_1 = n - 1
    # Cosets modulo {1, n-1}
    cosets = []
    seen = set()
    for u in units:
        if u not in seen:
            coset = frozenset([u, (n - u) % n])
            cosets.append(coset)
            seen.update(coset)
            
    # Find orders of coset elements
    coset_orders = {}
    for cos in cosets:
        rep = min(cos)
        # find order in quotient
        curr = rep
        order = 1
        while curr not in {1, inv_1}:
            curr = (curr * rep) % n
            order += 1
        coset_orders[rep] = order
        
    return units, cosets, coset_orders

def get_cycle_type(perm):
    n = len(perm)
    visited = [False] * n
    lens = []
    for i in range(n):
        if not visited[i]:
            curr = i
            l = 0
            while not visited[curr]:
                visited[curr] = True
                curr = perm[curr]
                l += 1
            lens.append(l)
    return tuple(sorted(lens))

def main():
    parser = argparse.ArgumentParser(description="Analyze Affine Macro-Orbits for Z_n Mosaic Partitions")
    parser.add_argument("-n", type=int, default=16, help="Cyclic modulus n (default: 16)")
    parser.add_argument("-k", "--parts", type=int, default=4, help="Number of blocks (default: 4)")
    parser.add_argument("-s", "--size", type=int, default=4, help="Size of each block (default: 4)")
    args = parser.parse_args()
    
    n = args.n
    k = args.parts
    s = args.size
    assert n == k * s, f"n ({n}) must equal k ({k}) * size ({s})"
    
    print(f"==================================================")
    print(f" Affine Macro-Orbit Analysis: Z_{n}, shape = z_{s}^{k}")
    print(f"==================================================")
    
    units, cosets, coset_orders = analyze_macro_group(n)
    print(f"Unit group (Z_{n})* order: {len(units)}, elements: {units}")
    print(f"Macro group G_macro = (Z_{n})* / {{+-1}} order: {len(cosets)}")
    print("Cosets and orders in G_macro:")
    for rep, order in sorted(coset_orders.items()):
        print(f"  Coset {{ {rep}, {(n - rep) % n} }}: order {order}")
        
    aff_elements = get_affine_group(n)
    print(f"Total Aff(Z_{n}) group order: {len(aff_elements)}")
    print("-" * 50)
    
    # Map each element to its cycle type and find representative perm
    element_cycle_types = {}
    rep_perms = {}
    for a, b in aff_elements:
        perm = [(a * x + b) % n for x in range(n)]
        ct = get_cycle_type(perm)
        element_cycle_types[(a, b)] = ct
        if ct not in rep_perms:
            rep_perms[ct] = perm
            
    print(f"Distinct permutation cycle types in Aff(Z_{n}): {len(rep_perms)}")
    fixed_by_cycle_type = {}
    for ct, perm in sorted(rep_perms.items(), key=lambda x: (len(x[0]), x[0])):
        cnt = count_fixed_partitions(perm, k, s)
        fixed_by_cycle_type[ct] = cnt
        num_el = sum(1 for c in element_cycle_types.values() if c == ct)
        print(f"  Cycle type {str(ct):35s}: {num_el:3d} elements, Fix(g) = {cnt:8d}")
        
    print("-" * 50)
    print("Burnside Orbit Counts for Symmetry Subgroups:")
    
    # 1. Cyclic C_n (a = 1)
    c_n_elements = [(1, b) for b in range(n)]
    sum_cn = sum(fixed_by_cycle_type[element_cycle_types[g]] for g in c_n_elements)
    orbits_cn = sum_cn // len(c_n_elements)
    print(f"  Cyclic C_{n:2d} (order {len(c_n_elements):3d}):       {orbits_cn:8d} orbits")
    
    # 2. Dihedral D_n (a in {1, n-1})
    d_n_elements = [(a, b) for a in [1, n - 1] for b in range(n)]
    sum_dn = sum(fixed_by_cycle_type[element_cycle_types[g]] for g in d_n_elements)
    orbits_dn = sum_dn // len(d_n_elements)
    print(f"  Dihedral D_{n:2d} (order {len(d_n_elements):3d}):     {orbits_dn:8d} orbits")
    
    # Check intermediate subgroups in G_macro
    # A subgroup of G_macro corresponds to a subgroup of (Z_n)* containing {1, -1}.
    # We can test all subgroups of (Z_n)* containing {1, -1}.
    from itertools import combinations
    
    subgroups = []
    # Identify unique subgroups of units containing {1, n-1}
    for r in range(1, len(cosets) + 1):
        for combo in combinations(cosets, r):
            u_set = set()
            for cos in combo:
                u_set.update(cos)
            # Check if closed under multiplication
            closed = True
            for u1 in u_set:
                for u2 in u_set:
                    if (u1 * u2) % n not in u_set:
                        closed = False
                        break
                if not closed:
                    break
            if closed:
                subgroups.append(sorted(list(u_set)))
                
    # Sort subgroups by size
    subgroups.sort(key=lambda s: len(s))
    
    for sub_u in subgroups:
        if len(sub_u) <= 2:
            continue # already did D_n
        h_elements = [(a, b) for a in sub_u for b in range(n)]
        sum_h = sum(fixed_by_cycle_type[element_cycle_types[g]] for g in h_elements)
        orbits_h = sum_h // len(h_elements)
        macro_sub_order = len(sub_u) // 2
        print(f"  Subgroup with units {str(sub_u):25s} (order {len(h_elements):3d}, |G_macro|={macro_sub_order}): {orbits_h:8d} orbits")
        
    print("-" * 50)
    print("Macro-Orbit Spectral Decomposition:")
    # If G_macro is cyclic C_4 (as in n=16), we can solve for c_1, c_2, c_4
    if len(cosets) == 4 and any(ord == 4 for ord in coset_orders.values()):
        # Find order 2 subgroup
        order_2_coset = [cos for cos in cosets if coset_orders[min(cos)] == 2][0]
        h2_units = sorted(list(set([1, n - 1]).union(order_2_coset)))
        h2_elements = [(a, b) for a in h2_units for b in range(n)]
        n_h2 = sum(fixed_by_cycle_type[element_cycle_types[g]] for g in h2_elements) // len(h2_elements)
        
        aff_elements = [(a, b) for a in units for b in range(n)]
        n_aff = sum(fixed_by_cycle_type[element_cycle_types[g]] for g in aff_elements) // len(aff_elements)
        
        n_dn = orbits_dn
        
        # System:
        # c1 + 2*c2 + 4*c4 = n_dn
        # c1 + 2*c2 + 2*c4 = n_h2
        # c1 +   c2 +   c4 = n_aff
        c4 = (n_dn - n_h2) // 2
        c2 = (n_h2 - n_aff) - c4
        c1 = n_aff - c2 - c4
        
        print(f"  Total D_{n} Orbits:               {n_dn:8d}")
        print(f"  Total Affine Macro-Orbits:       {n_aff:8d}")
        print(f"  • Monomers (Size 1 Fixed Points): {c1:8d}  (fixed by all multipliers in G_macro)")
        print(f"  • Doublets (Size 2 Cycles):       {c2:8d}  (fixed by mu_{min(order_2_coset)}, permuted by mu_3)")
        print(f"  • Quartets (Size 4 Cycles):       {c4:8d}  (full 4-cycles under mu_3)")
        print(f"  Verification check: {c1}*1 + {c2}*2 + {c4}*4 = {c1*1 + c2*2 + c4*4} == {n_dn}")
        print(f"  Total Macro-Orbits: {c1} + {c2} + {c4} = {c1 + c2 + c4} == {n_aff}")
        
        print("\n" + "=" * 50)
        print(f" Explicit Inventory of the {c1} Fixed-Point Macro-Orbits:")
        print("=" * 50)
        fixed_orbits = find_fixed_point_orbits(n, k, s)
        print(f"Found {len(fixed_orbits)} confirmed fixed-point D_{n} orbits:")
        
        def block_diffs(b, n):
            sb = sorted(list(b))
            k_pts = len(sb)
            diffs = [(sb[(i + 1) % k_pts] - sb[i]) % n for i in range(k_pts)]
            # Canonical cycle rep
            min_d = tuple(diffs)
            for shift in range(k_pts):
                cd = tuple(diffs[shift:] + diffs[:shift])
                if cd < min_d:
                    min_d = cd
            rd = tuple(reversed(diffs))
            for shift in range(k_pts):
                cd = tuple(rd[shift:] + rd[:shift])
                if cd < min_d:
                    min_d = cd
            return min_d

        for idx, orb in enumerate(sorted(fixed_orbits, key=lambda o: (len(o), sorted([sorted(list(b)) for b in list(o)[0]])))):
            rep = sorted(list(orb), key=lambda p: sorted([sorted(list(b)) for b in p]))[0]
            blocks = sorted([sorted(list(b)) for b in rep])
            diffs = [block_diffs(b, n) for b in blocks]
            # Check self-reversibility of blocks
            print(f"  FP #{idx+1:2d} (size {len(orb):2d}): blocks={blocks}")
            print(f"         block diff profiles: {diffs}")
    elif len(cosets) == 3:
        # For C_3 (e.g. n=9)
        aff_elements = [(a, b) for a in units for b in range(n)]
        n_aff = sum(fixed_by_cycle_type[element_cycle_types[g]] for g in aff_elements) // len(aff_elements)
        n_dn = orbits_dn
        # c1 + 3*c3 = n_dn
        # c1 +   c3 = n_aff
        c3 = (n_dn - n_aff) // 2
        c1 = n_aff - c3
        print(f"  Total D_{n} Orbits:               {n_dn:8d}")
        print(f"  Total Affine Macro-Orbits:       {n_aff:8d}")
        print(f"  • Monomers (Size 1 Fixed Points): {c1:8d}")
        print(f"  • Triplets (Size 3 Cycles):       {c3:8d}")
        print(f"  Verification check: {c1}*1 + {c3}*3 = {c1*1 + c3*3} == {n_dn}")
        print(f"  Total Macro-Orbits: {c1} + {c3} = {c1 + c3} == {n_aff}")
    
if __name__ == "__main__":
    main()
