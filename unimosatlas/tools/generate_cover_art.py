#!/usr/bin/env python3
"""
generate_cover_art.py - Generate High-Resolution TikZ Cover Artwork for Any Tetramer

Queries hexdec/data/hexadecality_index.txt for the specified tetramer (default: T10360)
and renders its 4 comosaics arranged in an anticlockwise Galois 4-cycle orbit:
  North (90 deg): Phase 1 (mu_1 = id)
  West (180 deg): Phase 2 (mu_3 = x3)
  South (270 deg): Phase 3 (mu_7 = x7)
  East (0 deg): Phase 4 (mu_5 = x5)

Author: Gemma Knee and Antigra Vitti
"""

import os
import sys
import math
import re
import argparse

def get_hexadecagon_coords(cx, cy, r):
    coords = []
    for k in range(16):
        # 12 o'clock is vertex 0, progressing clockwise
        ang = (90.0 - k * 22.5) * (math.pi / 180.0)
        coords.append((cx + r * math.cos(ang), cy + r * math.sin(ang)))
    return coords

def parse_partition_blocks(part_str):
    s = part_str.strip()
    if s.startswith('/'): s = s[1:]
    if s.endswith('/'): s = s[:-1]
    raw_blocks = s.split('/')
    blocks = []
    for b in raw_blocks:
        blocks.append([int(ch, 16) for ch in b.strip()])
    return blocks

def lookup_tetramer_data(target_id, index_path="hexdec/data/hexadecality_index.txt"):
    if not os.path.isfile(index_path):
        # Try finding relative to script dir
        script_dir = os.path.dirname(os.path.abspath(__file__))
        repo_dir = os.path.dirname(script_dir)
        index_path = os.path.join(repo_dir, "data", "hexadecality_index.txt")
        if not os.path.isfile(index_path):
            index_path = os.path.join(repo_dir, "hexdec", "data", "hexadecality_index.txt")

    target_id_upper = target_id.upper().strip()
    # Normalize e.g. T10360 -> T10360
    m = re.match(r'^T(\d+)$', target_id_upper)
    if m:
        target_id_upper = f"T{int(m.group(1)):05d}"

    with open(index_path, 'r', encoding='utf-8') as f:
        for line in f:
            if line.startswith(target_id_upper):
                # Example:
                # T10360  Tetramer  |O|=32  s=1  E= 614  /0139/278D/5BCE/46AF/ [nsnn] -> /5678/039B/2CDE/14AF/ [snnn] -> ...
                m_orb = re.search(r'\|O\|=\s*(\d+)', line)
                m_s = re.search(r's=\s*(\d+)', line)
                m_e = re.search(r'E=\s*(\d+)', line)
                
                orb_sz = int(m_orb.group(1)) if m_orb else 32
                s_count = int(m_s.group(1)) if m_s else 0
                energy = int(m_e.group(1)) if m_e else 0
                
                # Split phases by '->'
                after_e = line.split(f"E=")[1]
                after_e_val = re.split(r'\d+\s+', after_e.strip(), maxsplit=1)[1]
                phase_tokens = [tok.strip() for tok in after_e_val.split('->')]
                
                phases_data = []
                for p_tok in phase_tokens:
                    p_match = re.search(r'(/(?:[0-9A-Fa-f]{4}/){4})\s*\[([sn]{4})\]', p_tok)
                    if not p_match:
                        p_match = re.search(r'(/(?:[0-9A-Fa-f]+/)+)\s*\[([sn]+)\]', p_tok)
                    if p_match:
                        raw_part = p_match.group(1)
                        sig = p_match.group(2)
                        blocks = parse_partition_blocks(raw_part)
                        phases_data.append({
                            'partition': raw_part,
                            'signature': sig,
                            'blocks': blocks
                        })
                        
                return {
                    'id': target_id_upper,
                    'orbit_size': orb_sz,
                    's_count': s_count,
                    'energy': energy,
                    'phases': phases_data
                }
                
    raise KeyError(f"Tetramer {target_id} not found in {index_path}")

def generate_tikz(tetramer_info, orbit_r=3.80, disc_r=1.50, style="gradient",
                  height=0.22, depth_mode="radial", tilt_x=0.08, tilt_y=-0.20,
                  light_x=-0.6, light_y=0.8, shading_angle=45, rotate_shading=True):
    lines = []
    t_id = tetramer_info['id']
    phases_raw = tetramer_info['phases']

    lines.append(f"% TikZ Front Cover Centerpiece: Tetramer {t_id} (Style: {style})")
    lines.append("% Generated by hexdec/tools/generate_cover_art.py")
    lines.append("\\begin{tikzpicture}[>=latex, line join=round, line cap=round, scale=1.0]")
    
    # 4 Cardinal positions: North (90), West (180), South (270), East (0)
    # Anticlockwise sequence: Phase 1 (N) -> Phase 2 (W) -> Phase 3 (S) -> Phase 4 (E) -> Phase 1 (N)
    pos_angles = [90.0, 180.0, 270.0, 0.0]

    # Dynamic connecting arrows curving anticlockwise
    # At orbit_r = 3.80, disc_r = 1.50: subtended angle is ~23.3 deg.
    # Arcs run from 116 -> 154, 206 -> 244, 296 -> 334, 26 -> 64.
    arc_data = [
        (116, 154),
        (206, 244),
        (296, 334),
        (26, 64)
    ]

    for start_a, end_a in arc_data:
        lines.append(f"  % Anticlockwise Galois transition arc ({start_a} -> {end_a} deg)")
        lines.append(f"  \\draw[->, line width=2.2pt, blue!75!black] ({start_a}:{orbit_r:.2f}) arc ({start_a}:{end_a}:{orbit_r:.2f});")

    # Render each phase
    for idx, ang in enumerate(pos_angles):
        p_data = phases_raw[idx]
        ang_rad = ang * (math.pi / 180.0)
        cx = orbit_r * math.cos(ang_rad)
        cy = orbit_r * math.sin(ang_rad)
        coords = get_hexadecagon_coords(cx, cy, disc_r)
        
        lines.append(f"  % --- Phase {idx + 1} at {ang:.0f} deg ({cx:.2f}, {cy:.2f}) [{style}] ---")
        
        sig = p_data["signature"]
        blocks = p_data["blocks"]
        
        if style == "gradient":
            # Gradient shading across each tetragon
            for b_idx, blk in enumerate(blocks):
                is_sym = (sig[b_idx] == 's')
                poly_str = " -- ".join(f"({coords[v][0]:.3f},{coords[v][1]:.3f})" for v in blk) + " -- cycle"
                
                # Shading angle: rotating gradient along orbital positions
                eff_angle = (shading_angle + ang * 0.5) if rotate_shading else shading_angle
                
                if is_sym:
                    # Symmetric: bright cyan-blue to deep royal cobalt
                    c_left = "blue!45!white"
                    c_right = "blue!75!black"
                else:
                    # Chiral: soft rose-coral to deep ruby
                    c_left = "red!40!white"
                    c_right = "red!75!black"
                    
                lines.append(f"  \\shade[shading=axis, shading angle={eff_angle:.0f}, left color={c_left}, right color={c_right}, opacity=0.68] {poly_str};")
                lines.append(f"  \\draw[black!85, line width=0.55pt] {poly_str};")
                
        elif style == "tonal":
            # Stepped tonal values across the 4 blocks
            tonal_factors = [0.45, 0.60, 0.75, 0.90]
            for b_idx, blk in enumerate(blocks):
                is_sym = (sig[b_idx] == 's')
                poly_str = " -- ".join(f"({coords[v][0]:.3f},{coords[v][1]:.3f})" for v in blk) + " -- cycle"
                base_c = "mosaicblue" if is_sym else "mosaicpink"
                factor = tonal_factors[b_idx % 4]
                pct = int(factor * 100)
                lines.append(f"  \\fill[{base_c}!{pct}!black, fill opacity=0.65] {poly_str};")
                lines.append(f"  \\draw[black!85, line width=0.55pt] {poly_str};")
                
        elif style == "flat":
            # Pure flat colors with opacity
            for b_idx, blk in enumerate(blocks):
                is_sym = (sig[b_idx] == 's')
                fill_col = "mosaicblue" if is_sym else "mosaicpink"
                poly_str = " -- ".join(f"({coords[v][0]:.3f},{coords[v][1]:.3f})" for v in blk) + " -- cycle"
                lines.append(f"  \\fill[{fill_col}, fill opacity=0.62] {poly_str};")
                lines.append(f"  \\draw[black!85, line width=0.55pt] {poly_str};")
                
        elif style == "3d":
            # 3D Extrusion with depth-shaded sides
            l_len = math.hypot(light_x, light_y)
            lx = light_x / l_len if l_len > 1e-6 else -0.707
            ly = light_y / l_len if l_len > 1e-6 else 0.707
            
            if depth_mode == "radial":
                dx = -height * math.cos(ang_rad)
                dy = -height * math.sin(ang_rad)
            else:
                dx = tilt_x
                dy = tilt_y
                
            def block_depth_key(b_tuple):
                b_idx, blk = b_tuple
                pts = [coords[v] for v in blk]
                avg_x = sum(p[0] for p in pts) / len(pts)
                avg_y = sum(p[1] for p in pts) / len(pts)
                return avg_x * dx + avg_y * dy

            sorted_blocks = sorted(enumerate(blocks), key=block_depth_key)

            for b_idx, blk in sorted_blocks:
                is_sym = (sig[b_idx] == 's')
                fill_base_col = "mosaicblue" if is_sym else "mosaicpink"
                top_pts = [coords[v] for v in blk]
                bot_pts = [(x + dx, y + dy) for x, y in top_pts]
                n_pts = len(top_pts)
                
                for i in range(n_pts):
                    j = (i + 1) % n_pts
                    p1_top = top_pts[i]
                    p2_top = top_pts[j]
                    p2_bot = bot_pts[j]
                    p1_bot = bot_pts[i]
                    ex = p2_top[0] - p1_top[0]
                    ey = p2_top[1] - p1_top[1]
                    cross = ex * dy - ey * dx
                    if cross < -1e-6:
                        e_len = math.hypot(ex, ey)
                        nx = -ey / e_len if e_len > 1e-6 else 0.0
                        ny = ex / e_len if e_len > 1e-6 else 1.0
                        cos_theta = nx * lx + ny * ly
                        bright = 0.35 + 0.50 * ((cos_theta + 1.0) / 2.0)
                        pct = int(max(25, min(95, bright * 100)))
                        wall_col = f"{fill_base_col}!{pct}!black"
                        wall_poly = f"({p1_top[0]:.3f},{p1_top[1]:.3f}) -- ({p2_top[0]:.3f},{p2_top[1]:.3f}) -- ({p2_bot[0]:.3f},{p2_bot[1]:.3f}) -- ({p1_bot[0]:.3f},{p1_bot[1]:.3f}) -- cycle"
                        lines.append(f"  \\fill[{wall_col}, fill opacity=0.88] {wall_poly};")
                        lines.append(f"  \\draw[black!75, line width=0.45pt] {wall_poly};")
                
                top_poly = " -- ".join(f"({x:.3f},{y:.3f})" for x, y in top_pts) + " -- cycle"
                lines.append(f"  \\fill[{fill_base_col}, fill opacity=0.72] {top_poly};")
                lines.append(f"  \\draw[black!90, line width=0.55pt] {top_poly};")

    lines.append("\\end{tikzpicture}")
    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser(description="Generate TikZ Front Cover Artwork for Any Tetramer.")
    parser.add_argument("-t", "--tetramer", default="T10360", help="Tetramer ID (e.g. T10360, T20721)")
    parser.add_argument("-o", "--output", default="hexdec/tkz/fig_cover_t10360.tkz", help="Output .tkz file path")
    parser.add_argument("--orbit-radius", type=float, default=3.80, help="Radius of circular orbit (cm)")
    parser.add_argument("--disc-radius", type=float, default=1.50, help="Radius of each hexadecagon disc (cm)")
    parser.add_argument("--style", choices=["gradient", "tonal", "flat", "3d"], default="gradient", help="Rendering style")
    parser.add_argument("--shading-angle", type=float, default=45.0, help="Base shading angle in degrees")
    parser.add_argument("--no-rotate-shading", dest="rotate_shading", action="store_false", default=True, help="Use fixed shading angle across all phases")
    parser.add_argument("--height", type=float, default=0.22, help="3D extrusion height (cm)")
    parser.add_argument("--depth-mode", choices=["oblique", "radial"], default="radial", help="3D depth mode")
    parser.add_argument("--tilt-x", type=float, default=0.08, help="Oblique tilt X (cm)")
    parser.add_argument("--tilt-y", type=float, default=-0.20, help="Oblique tilt Y (cm)")
    args = parser.parse_args()

    t_info = lookup_tetramer_data(args.tetramer)
    tikz_code = generate_tikz(
        t_info,
        orbit_r=args.orbit_radius,
        disc_r=args.disc_radius,
        style=args.style,
        shading_angle=args.shading_angle,
        rotate_shading=args.rotate_shading,
        height=args.height,
        depth_mode=args.depth_mode,
        tilt_x=args.tilt_x,
        tilt_y=args.tilt_y
    )
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as f:
        f.write(tikz_code)
        f.write("\n")
    print(f"✓ Generated cover art for {t_info['id']} ({args.style} style): {args.output}")

if __name__ == "__main__":
    main()
