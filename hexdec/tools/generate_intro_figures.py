#!/usr/bin/env python3
"""
generate_intro_figures.py - Generate intro TikZ figures for Hexadecality

Produces:
1. hexdec/tkz/T00646.tkz (Figure 1.1: Clock-face convention, full mosaic, first block, and strides)
2. hexdec/tkz/T00646-1-dil.tkz (Figure 2.1: Successive inflations/dilations under mu_3)

Both strictly follow the polyatlas convention:
  Vertex 0 is at 90° (zenith), with vertices advancing clockwise:
  theta_k = 90° - k * 22.5°

Author: Gemma Knee & Antigra Vitti
Date: November 2026
"""

import math
import os

def get_coords(cx, cy, r=1.25):
    coords = []
    for k in range(16):
        ang = math.radians(90.0 - k * 22.5)
        coords.append((cx + r * math.cos(ang), cy + r * math.sin(ang)))
    return coords

def generate_t00646(output_path="hexdec/tkz/T00646.tkz"):
    r = 1.25
    shifts = [0.0, 3.2, 6.4, 9.6]
    
    p_blocks = [
        [0, 2, 7, 9],
        [1, 4, 10, 11],
        [3, 8, 12, 15],
        [5, 6, 13, 14]
    ]
    
    lines = []
    lines.append("% TikZ Figure 1.1: Clock-face convention, example partition P, and strides")
    lines.append("% Generated by hexdec/tools/generate_intro_figures.py (clockwise, vertex 0 at zenith)")
    lines.append("\\begin{tikzpicture}[line join=round, line cap=round, scale=1.0]")
    
    # --- Subfigure 1: Clock-face vertex numbering (x = shifts[0]) ---
    cx, cy = shifts[0], 0.0
    c1 = get_coords(cx, cy, r)
    wire1 = " -- ".join(f"({x:.3f},{y:.3f})" for x, y in c1) + " -- cycle"
    lines.append(f"  % Panel 1: Vertex coordinates 0..15")
    lines.append(f"  \\draw[gray!40, thick] {wire1};")
    for k in range(16):
        x, y = c1[k]
        lines.append(f"  \\node[circle, fill=white, draw=black!60, inner sep=1.2pt, font=\\tiny\\bfseries] at ({x:.3f},{y:.3f}) {{{k}}};")
        
    # --- Subfigure 2: Entire partition P (x = shifts[1]) ---
    cx, cy = shifts[1], 0.0
    c2 = get_coords(cx, cy, r)
    wire2 = " -- ".join(f"({x:.3f},{y:.3f})" for x, y in c2) + " -- cycle"
    lines.append(f"\n  % Panel 2: Full partition P")
    lines.append(f"  \\draw[gray!40, thick] {wire2};")
    for blk in p_blocks:
        pts = " -- ".join(f"({c2[v][0]:.3f},{c2[v][1]:.3f})" for v in blk) + " -- cycle"
        lines.append(f"  \\fill[mosaicblue, fill opacity=0.65] {pts};")
        lines.append(f"  \\draw[black, thick] {pts};")
    for vx, vy in c2:
        lines.append(f"  \\fill[black!70] ({vx:.3f},{vy:.3f}) circle (0.6pt);")

    # --- Subfigure 3: First block vertices (x = shifts[2]) ---
    cx, cy = shifts[2], 0.0
    c3 = get_coords(cx, cy, r)
    wire3 = " -- ".join(f"({x:.3f},{y:.3f})" for x, y in c3) + " -- cycle"
    b0 = p_blocks[0] # [0, 2, 7, 9]
    pts3 = " -- ".join(f"({c3[v][0]:.3f},{c3[v][1]:.3f})" for v in b0) + " -- cycle"
    lines.append(f"\n  % Panel 3: First block vertices")
    lines.append(f"  \\draw[gray!40, thick] {wire3};")
    lines.append(f"  \\fill[mosaicblue, fill opacity=0.65] {pts3};")
    lines.append(f"  \\draw[black, thick] {pts3};")
    for vx, vy in c3:
        lines.append(f"  \\fill[black!70] ({vx:.3f},{vy:.3f}) circle (0.6pt);")
    for v in b0:
        lines.append(f"  \\node[circle, fill=white, draw=black!60, inner sep=1.5pt, font=\\tiny\\bfseries] at ({c3[v][0]:.3f},{c3[v][1]:.3f}) {{{v}}};")

    # --- Subfigure 4: First block strides (x = shifts[3]) ---
    cx, cy = shifts[3], 0.0
    c4 = get_coords(cx, cy, r)
    wire4 = " -- ".join(f"({x:.3f},{y:.3f})" for x, y in c4) + " -- cycle"
    pts4 = " -- ".join(f"({c4[v][0]:.3f},{c4[v][1]:.3f})" for v in b0) + " -- cycle"
    lines.append(f"\n  % Panel 4: First block strides")
    lines.append(f"  \\draw[gray!40, thick] {wire4};")
    lines.append(f"  \\fill[mosaicblue, fill opacity=0.65] {pts4};")
    lines.append(f"  \\draw[black, thick] {pts4};")
    for vx, vy in c4:
        lines.append(f"  \\fill[black!70] ({vx:.3f},{vy:.3f}) circle (0.6pt);")
        
    strides = [
        (0, 2, 2),
        (2, 7, 5),
        (7, 9, 2),
        (9, 0, 7)
    ]
    for u, v, s_val in strides:
        mx = (c4[u][0] + c4[v][0]) / 2.0
        my = (c4[u][1] + c4[v][1]) / 2.0
        lines.append(f"  \\node[circle, fill=white, draw=black!60, inner sep=1.2pt, font=\\tiny\\bfseries] at ({mx:.3f},{my:.3f}) {{{s_val}}};")

    lines.append("\\end{tikzpicture}")
    
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"✓ Generated {output_path}")

def generate_t00646_1_dil(output_path="hexdec/tkz/T00646-1-dil.tkz"):
    r = 1.25
    shifts = [0.0, 3.0, 6.0, 9.0, 12.0]
    
    # 5 stages of successive inflation of {0, 2, 7, 9} under x -> 3x mod 16
    stages = [
        [0, 2, 7, 9],
        [0, 5, 6, 11],
        [0, 1, 2, 15],
        [0, 3, 6, 13],
        [0, 2, 7, 9]
    ]
    
    lines = []
    lines.append("% TikZ Figure 2.1: Successive inflations of subset {0, 2, 7, 9} under mu_3")
    lines.append("% Generated by hexdec/tools/generate_intro_figures.py (clockwise, vertex 0 at zenith)")
    lines.append("\\begin{tikzpicture}[line join=round, line cap=round, scale=0.88]")
    
    for idx, (cx, blk) in enumerate(zip(shifts, stages)):
        cy = 0.0
        coords = get_coords(cx, cy, r)
        wire = " -- ".join(f"({x:.3f},{y:.3f})" for x, y in coords) + " -- cycle"
        pts = " -- ".join(f"({coords[v][0]:.3f},{coords[v][1]:.3f})" for v in blk) + " -- cycle"
        
        lines.append(f"\n  % Stage {idx+1}: {blk}")
        lines.append(f"  \\draw[gray!40, thick] {wire};")
        lines.append(f"  \\fill[mosaicblue, fill opacity=0.65] {pts};")
        lines.append(f"  \\draw[black, thick] {pts};")
        for vx, vy in coords:
            lines.append(f"  \\fill[black!70] ({vx:.3f},{vy:.3f}) circle (0.5pt);")
        for v in blk:
            lines.append(f"  \\node[circle, fill=white, draw=black!60, inner sep=1.2pt, font=\\tiny\\bfseries] at ({coords[v][0]:.3f},{coords[v][1]:.3f}) {{{v}}};")
            
    lines.append("\\end{tikzpicture}")
    
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"✓ Generated {output_path}")

def main():
    generate_t00646()
    generate_t00646_1_dil()

if __name__ == "__main__":
    main()
